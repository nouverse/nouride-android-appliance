#!/usr/bin/env bash
# Builds proot (termux/proot, the release Termux ships) and its loader for arm64 Android
# with the NDK, talloc linked in statically, and puts them where Gradle packages them:
#
#   app/src/main/jniLibs/arm64-v8a/libproot.so          the proot executable
#   app/src/main/jniLibs/arm64-v8a/libproot-loader.so   the loader proot starts every guest program with
#
# Android installs lib*.so from the APK into the app's nativeLibraryDir, the one place an app
# may execute files from. The names are a packaging trick: both are executables, not libraries.
#
# Differences from Termux's build: talloc is static (no RUNPATH into /data/data/com.termux),
# no libandroid-shmem (it only shares SysV shm with Termux's own processes), and only the
# 64-bit loader is shipped. The app always sets PROOT_LOADER and PROOT_TMP_DIR, so the
# compiled-in loader directory below is never used.
#
#   . <toolchain>/env.sh && scripts/build-proot.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=assets.lock
. "$ROOT/scripts/assets.lock"

: "${ANDROID_NDK_HOME:?source the toolchain env.sh first}"
grep -q "Pkg.Revision = $NDK_VERSION" "$ANDROID_NDK_HOME/source.properties" \
  || { echo "NDK at $ANDROID_NDK_HOME is not $NDK_VERSION" >&2; exit 1; }

TOOLS="$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin"
export CC="$TOOLS/aarch64-linux-android$NDK_API-clang"
export AR="$TOOLS/llvm-ar"
WORK="$ROOT/build/proot"
OUT="$ROOT/app/src/main/jniLibs/arm64-v8a"
UNUSED_LOADER_DIR=/data/data/tech.nouverse.nouride.android/files/libexec/proot

fetch() { # url sha256 file
  if [ ! -f "$3" ]; then
    curl -fsSL --retry 5 --retry-all-errors --connect-timeout 30 -o "$3.part" "$1"
    mv "$3.part" "$3"
  fi
  echo "$2  $3" | sha256sum -c --quiet -
}

rm -rf "$WORK/src" && mkdir -p "$WORK/dl" "$WORK/src" "$WORK/talloc"
fetch "$TALLOC_URL" "$TALLOC_SHA256" "$WORK/dl/talloc-$TALLOC_VERSION.tar.gz"
fetch "$PROOT_URL" "$PROOT_SHA256" "$WORK/dl/proot-$PROOT_VERSION.zip"

# talloc: Termux's cross-answers (packages/libtalloc/build.sh), then the objects into a static archive.
tar -xzf "$WORK/dl/talloc-$TALLOC_VERSION.tar.gz" -C "$WORK/src"
(
  cd "$WORK/src/talloc-$TALLOC_VERSION"
  cat > cross-answers.txt <<'EOF'
Checking uname sysname type: "Linux"
Checking uname machine type: "dontcare"
Checking uname release type: "dontcare"
Checking uname version type: "dontcare"
Checking simple C program: OK
building library support: OK
Checking for large file support: OK
Checking for -D_FILE_OFFSET_BITS=64: OK
Checking for WORDS_BIGENDIAN: OK
Checking for C99 vsnprintf: OK
Checking for HAVE_SECURE_MKSTEMP: OK
rpath library support: OK
-Wl,--version-script support: FAIL
Checking correct behavior of strtoll: OK
Checking correct behavior of strptime: OK
Checking for HAVE_IFACE_GETIFADDRS: OK
Checking for HAVE_IFACE_IFCONF: OK
Checking for HAVE_IFACE_IFREQ: OK
Checking getconf LFS_CFLAGS: OK
Checking for large file support without additional flags: OK
Checking for working strptime: OK
Checking for HAVE_SHARED_MMAP: OK
Checking for HAVE_MREMAP: OK
Checking for HAVE_INCOHERENT_MMAP: OK
Checking getconf large file support flags work: OK
EOF
  ./configure --prefix="$WORK/talloc" --disable-rpath --disable-python \
    --cross-compile --cross-answers=cross-answers.txt > "$WORK/talloc-configure.log"
  make > "$WORK/talloc-make.log"
  mkdir -p "$WORK/talloc/lib" "$WORK/talloc/include"
  rm -f "$WORK/talloc/lib/libtalloc.a"
  # waf compiles talloc.c and libreplace's replace.c once per target, identically: one of each.
  "$AR" rcs "$WORK/talloc/lib/libtalloc.a" \
    "$(ls bin/default/talloc.c.*.o | head -1)" "$(ls bin/default/lib/replace/replace.c.*.o | head -1)"
  cp talloc.h "$WORK/talloc/include/"
)

# proot, with the flags Termux adds (ARG_MAX, VERSION); the 32-bit loader is not built.
# Two steps differ from a plain `make`:
# - extension/ashmem_memfd/ashmem_memfd.c calls strcmp and memset without <string.h>, which
#   this NDK's clang refuses (implicit declaration): the include is added to that one file.
# - loader/loader-info.c is generated by an awk script that needs gawk's strtonum; it is
#   written here instead, from the same two symbols of the built loader.
unzip -q "$WORK/dl/proot-$PROOT_VERSION.zip" -d "$WORK/src"
(
  cd "$WORK/src/proot-$PROOT_VERSION"
  sed -i '1i #include <string.h>' src/extension/ashmem_memfd/ashmem_memfd.c
  export CFLAGS="-I$WORK/talloc/include"
  export CPPFLAGS="-DARG_MAX=131072 -DVERSION=\\\"$PROOT_VERSION\\\""
  export LDFLAGS="-L$WORK/talloc/lib"
  build() {
    make -C src "$1" \
      STRIP="$TOOLS/llvm-strip" OBJCOPY="$TOOLS/llvm-objcopy" OBJDUMP="$TOOLS/llvm-objdump" \
      PROOT_UNBUNDLE_LOADER="$UNUSED_LOADER_DIR" HAS_LOADER_32BIT= >> "$WORK/proot-make.log"
  }
  : > "$WORK/proot-make.log"
  build loader/loader
  symbol() { "$TOOLS/llvm-readelf" -s src/loader/loader | awk -v name="$1" '$8 == name { print $2 }'; }
  workaround=$(symbol pokedata_workaround)
  start=$(symbol _start)
  [ -n "$workaround" ] && [ -n "$start" ] || { echo "loader symbols not found" >&2; exit 1; }
  printf '#include <unistd.h>\nconst ssize_t offset_to_pokedata_workaround=%d;\n' \
    $((0x$workaround - 0x$start)) > src/loader/loader-info.c
  build proot
  mkdir -p "$OUT"
  "$TOOLS/llvm-strip" -o "$OUT/libproot.so" src/proot
  "$TOOLS/llvm-strip" -o "$OUT/libproot-loader.so" src/loader/loader
)

(cd "$OUT" && sha256sum libproot.so libproot-loader.so)
